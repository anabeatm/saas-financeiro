import { Lightbulb, Loader2, Sparkles } from "lucide-react";
import { useState } from "react";
import AiService from "../../../services/AiService";
import { getErrorMessage } from "../../utils/errors";

// AI reading of the period shown in the report. Generated on request (it uses the AI quota);
// the parent gives it a `key` per wallet + period, so changing either clears the previous text.
export default function AiInsightsCard({ walletId, startDate, endDate }) {
  const [insights, setInsights] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const generate = async () => {
    setLoading(true);
    setError("");
    try {
      setInsights(await new AiService().getInsights(walletId, startDate, endDate));
    } catch (err) {
      setError(getErrorMessage(err, "Could not generate the insights right now."));
    } finally {
      setLoading(false);
    }
  };

  return (
    <section className="mt-6 rounded-xl border border-[#a88d6f]/30 bg-[#a88d6f]/5 p-5 print:border-gray-200 print:bg-white">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <h2 className="flex items-center gap-2 text-sm font-bold uppercase tracking-wider text-[#a88d6f]">
          <Sparkles size={16} />
          AI insights
        </h2>
        <button
          onClick={generate}
          disabled={loading}
          className="flex cursor-pointer items-center gap-2 rounded-lg bg-[#a88d6f] px-3 py-1.5 text-xs font-semibold text-white hover:bg-[#91755a] disabled:opacity-60 print:hidden"
        >
          {loading ? <Loader2 size={14} className="animate-spin" /> : <Sparkles size={14} />}
          {insights ? "Generate again" : "Generate insights"}
        </button>
      </div>

      {!insights && !error && !loading && (
        <p className="mt-3 text-sm text-gray-500">
          Get a short summary of this period and practical tips, written by AI from the totals of the
          report (descriptions and member names are not sent).
        </p>
      )}

      {loading && <p className="mt-3 text-sm text-gray-500">Analysing the period...</p>}

      {error && (
        <p role="alert" className="mt-3 text-sm text-red-600">
          {error}
        </p>
      )}

      {insights && !loading && (
        <div className="mt-3 flex flex-col gap-3">
          <p className="text-sm leading-relaxed text-gray-700">{insights.summary}</p>
          {insights.tips.length > 0 && (
            <ul className="flex flex-col gap-2">
              {insights.tips.map((tip) => (
                <li key={tip} className="flex gap-2 text-sm text-gray-700">
                  <Lightbulb size={16} className="mt-0.5 shrink-0 text-[#a88d6f]" />
                  <span>{tip}</span>
                </li>
              ))}
            </ul>
          )}
          {insights.generatedByAi && (
            <p className="text-xs text-gray-400">
              Generated by AI (Google Gemini). It can make mistakes; check the numbers above.
            </p>
          )}
        </div>
      )}
    </section>
  );
}
